/** The option list a lesson shows for a control (optionally a subset). */
export function controlOptions(entry) {
  const id = typeof entry === 'string' ? entry : entry.id;
  const all = CONTROLS[id].options;
  return typeof entry === 'string' || !entry.only ? all : all.filter(o => entry.only.includes(o.value));
}
export const controlId = (entry) => (typeof entry === 'string' ? entry : entry.id);
export const controlValue = (id, c) => (CONTROLS[id].get ? CONTROLS[id].get(c) : c[id]);
export const controlSet = (id, v) => (CONTROLS[id].set ? CONTROLS[id].set(v) : { [id]: v });

